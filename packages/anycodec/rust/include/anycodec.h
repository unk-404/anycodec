/**
 * Creates a verbatim retrieve decoder for `codec`.
 *
 * Returns NULL and sets the thread-local error when `codec` is not a known codec
 * id.
 */
struct AnyCodecDecoder *anycodec_passthrough_decoder_new(uint32_t codec);

